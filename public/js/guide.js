    function normalizeRole(role) {
        // 未知／未登入的角色一律當訪客：說明一定要看得到，但只給最低權限的內容
        return VALID_ROLES.includes(role) ? role : 'guest';
    }

    function sectionsFor(role) {
        const key = normalizeRole(role);
        return GUIDE_SECTIONS.filter((s) => s.roles.includes(key));
    }

    function checklistFor(role) {
        return (ADMIN_CHECKLIST.roles.includes(normalizeRole(role))) ? ADMIN_CHECKLIST : null;
    }

    function searchSections(sections, query) {
        const q = String(query || '').trim().toLowerCase();
        if (!q) return sections;
        return sections.filter((s) => {
            const haystack = [s.title, s.intro, s.tip || ''].concat(s.steps || []).join(' ').toLowerCase();
            return haystack.includes(q);
        });
    }

    function groupSections(sections) {
        const groups = [];
        for (const s of sections) {
            let g = groups.find((x) => x.name === s.group);
            if (!g) { g = { name: s.group, sections: [] }; groups.push(g); }
            g.sections.push(s);
        }
        return groups;
    }

    /* 給測試與除錯用的摘要 */
    function statusSummary() {
        const byRole = {};
        ['guest', 'user', 'test', 'admin', 'super_admin', 'web_owner'].forEach((r) => {
            byRole[r] = { sections: sectionsFor(r).length, checklist: Boolean(checklistFor(r)) };
        });
        return {
            sections: GUIDE_SECTIONS.length,
            checklistItems: ADMIN_CHECKLIST.items.length,
            byRole
        };
    }

    return {
        GUIDE_SECTIONS, ADMIN_CHECKLIST,
        sectionsFor, checklistFor, searchSections, groupSections, statusSummary
    };
